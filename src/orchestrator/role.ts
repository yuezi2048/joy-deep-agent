/**
 * 角色（Role）：一类子智能体的定义。
 *
 * 角色决定三件事：**干什么**（description，给规划模型看）、**怎么想**（systemPrompt）、
 * **能用什么工具**（allowedTools）。计划里的 `steps[].role` 用 `name` 点名。
 */
export interface AgentRole {
  /** 稳定标识，计划里用它点名；改名会让已落盘的历史计划失效 */
  name: string;
  /** 展示名 */
  title: string;
  /** 职责说明，会写进规划提示，模型靠它决定把活派给谁 */
  description: string;
  /** 该角色子智能体的系统提示 */
  systemPrompt: string;
  /**
   * 允许使用的工具名白名单。**不传 = 全部工具**；传 `[]` = 没有任何工具。
   * 名字必须真实存在：写错会在派发时立刻报错，而不是静默少一个工具。
   */
  allowedTools?: readonly string[];
}

